// РњРµС…Р°РЅРёР·Рј: СЃРµСЂРІРµСЂ СЃРѕР·РґР°С‘С‚ Р·Р°РїРёСЃСЊ РІ С‚Р°Р±Р»РёС†Рµ sessions (РІ MSSQL), РѕС‚РґР°С‘С‚ РєР»РёРµРЅС‚Сѓ
// cookie СЃ ID СЌС‚РѕР№ Р·Р°РїРёСЃРё. РџСЂРё СЃР»РµРґСѓСЋС‰РµРј Р·Р°РїСЂРѕСЃРµ РєР»РёРµРЅС‚ РїСЂРёСЃС‹Р»Р°РµС‚ cookie,
